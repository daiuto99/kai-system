export const STATUS_ORDER = { red: 0, yellow: 1, green: 2 }

export function domainOverallStatus(domain) {
  const statuses = Object.values(domain.aspects).map(a => a.status)
  if (statuses.includes('red')) return 'red'
  if (statuses.includes('yellow')) return 'yellow'
  return 'green'
}

export function domainsNeedingAttention(domains) {
  return domains
    .filter(d => domainOverallStatus(d) !== 'green')
    .sort((a, b) => STATUS_ORDER[domainOverallStatus(a)] - STATUS_ORDER[domainOverallStatus(b)])
}
